-- Arcade Atlas Neon PostgreSQL schema.
-- Scores are TEXT to preserve exact values up to 500 digits.
CREATE TABLE IF NOT EXISTS scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_name TEXT NOT NULL CHECK (char_length(player_name) BETWEEN 1 AND 24),
  game_title TEXT NOT NULL CHECK (char_length(game_title) BETWEEN 1 AND 60),
  score TEXT NOT NULL CHECK (char_length(score) BETWEEN 1 AND 500 AND score ~ '^[0-9]+$'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_scores_created_at ON scores(created_at DESC, id ASC);
CREATE INDEX IF NOT EXISTS idx_scores_game_title ON scores(game_title);
CREATE INDEX IF NOT EXISTS idx_scores_game_player_recent ON scores (lower(trim(game_title)), lower(trim(player_name)), created_at DESC, id ASC);

CREATE TABLE IF NOT EXISTS score_ip_records (
  score_id BIGINT PRIMARY KEY REFERENCES scores(id) ON DELETE CASCADE,
  ip_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS leaderboard_top_scores (
  game_key TEXT NOT NULL,
  rank SMALLINT NOT NULL CHECK (rank BETWEEN 1 AND 3),
  id BIGINT NOT NULL,
  player_name TEXT NOT NULL,
  game_title TEXT NOT NULL,
  score TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (game_key, rank)
);
CREATE INDEX IF NOT EXISTS idx_leaderboard_top_scores_game_rank ON leaderboard_top_scores(game_key, rank);

-- Rebuild the top three for one game after every inserted score.
CREATE OR REPLACE FUNCTION refresh_arcade_leaderboard_top3(p_game_title TEXT)
RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE v_game_key TEXT := lower(trim(p_game_title));
BEGIN
  DELETE FROM leaderboard_top_scores WHERE game_key = v_game_key;
  IF v_game_key = 'cookie clicker' THEN
    INSERT INTO leaderboard_top_scores(game_key, rank, id, player_name, game_title, score, created_at)
    WITH per_player AS (
      SELECT DISTINCT ON (lower(trim(player_name))) id, player_name, game_title, score, created_at,
        CASE WHEN ltrim(score, '0') = '' THEN '0' ELSE ltrim(score, '0') END AS normalized_score
      FROM scores WHERE lower(trim(game_title)) = v_game_key
      ORDER BY lower(trim(player_name)),
        length(CASE WHEN ltrim(score, '0') = '' THEN '0' ELSE ltrim(score, '0') END) DESC,
        CASE WHEN ltrim(score, '0') = '' THEN '0' ELSE ltrim(score, '0') END DESC,
        created_at DESC, id ASC
    ), ranked AS (
      SELECT *, row_number() OVER (ORDER BY length(normalized_score) DESC, normalized_score DESC, created_at DESC, id ASC) AS game_rank FROM per_player
    )
    SELECT v_game_key, game_rank::smallint, id, player_name, game_title, score, created_at FROM ranked WHERE game_rank <= 3;
  ELSIF v_game_key IN ('minecraft', 'retro bowl time', 'blocky combat swat time') THEN
    INSERT INTO leaderboard_top_scores(game_key, rank, id, player_name, game_title, score, created_at)
    WITH totals AS (
      SELECT lower(trim(player_name)) AS player_key, sum(score::numeric) AS total_score, max(created_at) AS latest_created_at
      FROM scores WHERE lower(trim(game_title)) = v_game_key GROUP BY lower(trim(player_name))
    ), latest AS (
      SELECT t.*, s.id, s.player_name, s.game_title FROM totals t
      JOIN LATERAL (
        SELECT id, player_name, game_title FROM scores
        WHERE lower(trim(game_title)) = v_game_key AND lower(trim(player_name)) = t.player_key
        ORDER BY created_at DESC, id ASC LIMIT 1
      ) s ON true
    ), ranked AS (
      SELECT *, row_number() OVER (ORDER BY total_score DESC, latest_created_at DESC, player_key ASC) AS game_rank FROM latest
    )
    SELECT v_game_key, game_rank::smallint, id, player_name, game_title, total_score::numeric::text, latest_created_at FROM ranked WHERE game_rank <= 3;
  ELSE
    INSERT INTO leaderboard_top_scores(game_key, rank, id, player_name, game_title, score, created_at)
    SELECT v_game_key, row_number() OVER (
      ORDER BY length(CASE WHEN ltrim(score, '0') = '' THEN '0' ELSE ltrim(score, '0') END) DESC,
        CASE WHEN ltrim(score, '0') = '' THEN '0' ELSE ltrim(score, '0') END DESC, created_at DESC, id ASC
    )::smallint, id, player_name, game_title, score, created_at
    FROM scores WHERE lower(trim(game_title)) = v_game_key AND (v_game_key <> 'slope' OR score::numeric <= 1500)
    ORDER BY length(CASE WHEN ltrim(score, '0') = '' THEN '0' ELSE ltrim(score, '0') END) DESC,
      CASE WHEN ltrim(score, '0') = '' THEN '0' ELSE ltrim(score, '0') END DESC, created_at DESC, id ASC LIMIT 3;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION scores_refresh_top3_trigger()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  PERFORM refresh_arcade_leaderboard_top3(NEW.game_title);
  RETURN NEW;
END;
$$;

CREATE TRIGGER scores_refresh_top3
AFTER INSERT ON scores
FOR EACH ROW EXECUTE FUNCTION scores_refresh_top3_trigger();
